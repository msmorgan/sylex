use super::SemanticType;
use crate::ast;

macro_rules! syntax_types {
    ($($ty:ident),* $(,)?) => {
        $(impl SemanticType for ast::$ty {
            fn semantic_type() -> String { stringify!($ty).into() }
        })*
        pub(super) fn debug_value(ty: &str, value: serde_json::Value) -> super::Result<Box<dyn std::fmt::Debug>> {
            match ty {
                $(stringify!($ty) => super::snapshot::decode::<ast::$ty>(value),)*
                _ => super::snapshot::composite(ty,value),
            }
        }
    };
}
